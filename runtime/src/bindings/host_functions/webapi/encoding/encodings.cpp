    consteval bool encodingSpecsAreConsistent()
    {
        for (size_t index = 0; index < encodingSpecs.size(); ++index) {
            const auto& spec = encodingSpecs[index];
            if (spec.encoding != static_cast<TextEncoding>(index))
                return false;
            if ((spec.kind == DecoderKind::SingleByte) != (spec.single_byte_index != nullptr))
                return false;
            if ((spec.kind == DecoderKind::Icu) != (spec.icu_converter != nullptr))
                return false;
        }
        return true;
    }
    static_assert(encodingSpecsAreConsistent());

